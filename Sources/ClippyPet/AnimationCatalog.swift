    static let playableAnimations = animations.filter { $0.name != "RestPose" }

    static var frameCount: Int {
        animations.reduce(0) { $0 + $1.frames.count }
    }

    static func animation(named name: String) -> SpriteAnimation? {
        animations.first { $0.name == name }
    }

    static func route(forAnimation name: String, frameIndex: Int) -> SpriteRoute? {
        routes[name]?[frameIndex]
    }

    static var routeCount: Int {
        routes.values.reduce(0) { $0 + $1.count }
    }

    static func routeValidationErrors() -> [String] {
        let frameCounts = Dictionary(
            uniqueKeysWithValues: animations.map { ($0.name, $0.frames.count) }
        )
        var errors: [String] = []

        for name in routes.keys.sorted() {
            guard let frameCount = frameCounts[name] else {
                errors.append("Route table references unknown animation \(name).")
                continue
            }
            guard let animationRoutes = routes[name] else { continue }

            for frameIndex in animationRoutes.keys.sorted() {
                guard frameIndex >= 0, frameIndex < frameCount else {
                    errors.append("\(name) has a route for invalid frame \(frameIndex).")
                    continue
                }
                guard let animationRoute = animationRoutes[frameIndex] else { continue }

                if let exitBranch = animationRoute.exitBranch,
                   !(0..<frameCount).contains(exitBranch) {
                    errors.append(
                        "\(name) frame \(frameIndex) has invalid exit target \(exitBranch)."
                    )
                }

                var totalWeight = 0
                for branch in animationRoute.branches {
                    if !(0..<frameCount).contains(branch.frameIndex) {
                        errors.append(
                            "\(name) frame \(frameIndex) has invalid branch target " +
                                "\(branch.frameIndex)."
                        )
                    }
                    if !(1...100).contains(branch.weight) {
                        errors.append(
                            "\(name) frame \(frameIndex) has invalid branch weight " +
                                "\(branch.weight)."
                        )
                    }
                    totalWeight += branch.weight
                }

                if totalWeight > 100 {
                    errors.append(
                        "\(name) frame \(frameIndex) has branch weight total \(totalWeight)."
                    )
                }
            }
        }

        return errors
    }
